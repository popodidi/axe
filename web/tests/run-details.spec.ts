test("task run: times on every entry and a details rail with prompts", async ({
  page,
}) => {
  await fixture(page, "task");
  await page.goto("/?server=http://axe.test&run=11");
  const dialog = page.getByRole("dialog", { name: "Run log" });
  const details = dialog.getByRole("complementary", { name: "Run details" });
  await expect(details).toBeVisible();
  await expect(
    dialog.getByRole("button", { name: "Hide details" }),
  ).toHaveAttribute("aria-expanded", "true");
  // Every entry carries a time with its full form on hover; tool calls show
  // name, arguments, status and time taken.
  const entries = dialog.locator("article");
  await expect(entries).toHaveCount(5);
  await expect(entries.locator("time")).toHaveCount(5);
  const tool = dialog.locator('article[data-kind="tool"]');
  await expect(tool.locator("summary")).toContainText("Bash");
  await expect(tool.locator("summary")).toContainText("axe task show 3");
  await expect(tool.locator("summary")).toContainText("Completed · 2s");
  await expect(tool.locator("time")).toHaveAttribute(
    "datetime",
    "2026-11-25T02:00:03.000Z",
  );
  expect(await tool.locator("time").getAttribute("title")).toContain(
    "into the run",
  );
  await expect(dialog.locator('article[data-kind="system"]')).toHaveCount(2);
  await expect(dialog.locator('article[data-error="true"]')).toContainText(
    "Permission denied",
  );
  for (const text of [
    "claude-1",
    "claude-code",
    "claude-fixture-5",
    "high",
    "2.1.325",
    "af1403f5-fixture",
    "3m 05s",
    "$1.50",
    "ui, runtime:claude-1",
    "/runs/task-3",
  ])
    await expect(details).toContainText(text);
  await expect(
    details.getByRole("link", { name: /#3 Fixture task/ }),
  ).toBeVisible();
  await details.getByText("User prompt").click();
  await expect(
    details.getByText("Work task 3 in project atlas."),
  ).toBeVisible();
  await details.getByText("System prompt · run instructions").click();
  await expect(details.getByText("Generated by axe.")).toBeVisible();
  for (const theme of ["dark", "light"]) {
    await page.evaluate(
      (t) => (document.documentElement.dataset.theme = t),
      theme,
    );
    await page.screenshot({
      path: test.info().outputPath(`task-details-${theme}.png`),
    });
  }
  // The task link goes to the task's runs without leaving the dashboard.
  await details.getByRole("link", { name: /#3 Fixture task/ }).click();
  await expect(dialog).toHaveCount(0);
  expect(new URL(page.url()).searchParams.get("task")).toBe("3");
  expect(new URL(page.url()).searchParams.get("server")).toBe(
    "http://axe.test",
  );
});

