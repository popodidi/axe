test("narrow windows open the details on demand, without overflow", async ({
  page,
}) => {
  await fixture(page, "task");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/?server=http://axe.test&run=11");
  const dialog = page.getByRole("dialog", { name: "Run log" });
  const details = dialog.getByRole("complementary", { name: "Run details" });
  await expect(dialog.getByText("Reading the spec first.")).toBeVisible();
  await expect(details).toBeHidden();
  const toggle = dialog.getByRole("button", { name: "Details", exact: true });
  await expect(toggle).toHaveAttribute("aria-expanded", "false");
  await toggle.click();
  await expect(details).toBeVisible();
  await expect(dialog.getByLabel("Log output")).toBeHidden();
  expect(
    await dialog.evaluate((el) => el.scrollWidth <= window.innerWidth),
  ).toBe(true);
  await page.screenshot({ path: test.info().outputPath("details-phone.png") });
  await dialog.getByRole("button", { name: "Hide details" }).click();
  await expect(dialog.getByLabel("Log output")).toBeVisible();
});

const railWidth = (page: Page) =>
  page
    .locator("#run-details")
    .evaluate((el) => Math.round(el.getBoundingClientRect().width));

test("the details rail resizes like the side panes and keeps its width", async ({
  page,
}) => {
  await fixture(page, "task");
  await page.goto("/?server=http://axe.test&run=11");
  const dialog = page.getByRole("dialog", { name: "Run log" });
  const handle = dialog.getByRole("separator", { name: "Resize run details" });
  await expect(handle).toHaveAttribute("aria-controls", "run-details");
  const start = await railWidth(page);
  expect(start).toBe(528);
  await expect(handle).toHaveAttribute("aria-valuenow", String(start));
  expect(Number(await handle.getAttribute("aria-valuemin"))).toBe(360);
  // The trace keeps at least 360px of the 1440px window.
  expect(Number(await handle.getAttribute("aria-valuemax"))).toBe(1440 - 360);

  // Drag left by 200px widens the rail by 200px.
  const box = (await handle.boundingBox())!;
  const y = box.y + box.height / 2;
  await page.mouse.move(box.x + box.width / 2, y);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 - 100, y, { steps: 5 });
  await page.mouse.move(box.x + box.width / 2 - 200, y, { steps: 5 });
  await page.mouse.up();
  await expect.poll(() => railWidth(page)).toBe(start + 200);
  await dialog.getByText("System prompt · run instructions").click();
  await expect(dialog.getByText("Generated by axe.")).toBeVisible();
  await page.mouse.move(box.x - 400, y);
  await page.waitForTimeout(400);
  await page.screenshot({
    path: test.info().outputPath("run-details-wide.png"),
  });

  // Past either edge it stops at the bounds; Home/End jump to them.
  await page.mouse.move(box.x - 200 + box.width / 2, y);
  await page.mouse.down();
  await page.mouse.move(5, y, { steps: 5 });
  await page.mouse.up();
  await expect.poll(() => railWidth(page)).toBe(1440 - 360);
  await handle.focus();
  await page.keyboard.press("Home");
  await expect.poll(() => railWidth(page)).toBe(360);
  await page.keyboard.press("Shift+ArrowLeft");
  await expect.poll(() => railWidth(page)).toBe(424);

  // The width persists across reloads and runs; double-click resets it.
  await page.reload();
  await expect.poll(() => railWidth(page)).toBe(424);
  await dialog
    .getByRole("separator", { name: "Resize run details" })
    .dblclick();
  await expect.poll(() => railWidth(page)).toBe(start);
});

test("prompts show rendered Markdown or raw text, and the choice persists", async ({
  page,
}) => {
  await fixture(page, "task");
  await page.goto("/?server=http://axe.test&run=11");
  const details = page.getByRole("complementary", { name: "Run details" });
  await details.getByText("System prompt · run instructions").click();
  const view = details.getByRole("group", {
    name: "System prompt · run instructions view",
  });
  // Rendered by default: the heading is a heading, not "# ..." text.
  await expect(view.getByRole("button", { name: "Rendered" })).toHaveAttribute(
    "aria-pressed",
    "true",
  );
  await expect(
    details.getByRole("heading", { name: "Task 3: fixture" }),
  ).toBeVisible();
  await expect(details.getByText("Generated by axe.")).toBeVisible();
  await page.waitForTimeout(400);
  await page.screenshot({
    path: test.info().outputPath("system-prompt-rendered.png"),
  });
  await view.getByRole("button", { name: "Raw" }).click();
  await expect(view.getByRole("button", { name: "Raw" })).toHaveAttribute(
    "aria-pressed",
    "true",
  );
  await expect(details.getByText("# Task 3: fixture")).toBeVisible();
  await expect(
    details.getByRole("heading", { name: "Task 3: fixture" }),
  ).toHaveCount(0);

  // Each prompt keeps its own choice; both carry to the next run.
  await details.getByText("User prompt").click();
  await expect(
    details
      .getByRole("group", { name: "User prompt view" })
      .getByRole("button", { name: "Rendered" }),
  ).toHaveAttribute("aria-pressed", "true");
  await page.goto("/?server=http://axe.test&run=12");
  await details.getByText("System prompt · run instructions").click();
  await expect(details.getByText("# Task 3: fixture")).toBeVisible();
});
